def north_partition(home, registry):
    doc = pilot.checked(home/NORTH_MASK, NORTH_MASK_SHA, 2*1024**2)
    if (doc.get('format') != 'awft-north-connected-preservation-mask:1'
            or doc.get('checkpoint_sha256') != NORTH_SOURCE_CHECKPOINT_SHA or doc.get('north_south_components_disjoint') is not True
            or doc.get('native_plan') is not False or doc.get('extra_skirt_metres_in_file') != 0
            or any(str(doc.get(k)) != str(registry[k]) for k in ('seed', 'world_path'))):
        raise UserError('Exact independently separated1m north-bank preservation mask required')
    columns = set(map(tuple, doc['connected_columns_xz']))
    if len(columns) != doc['connected_columns'] or len(columns) != 37284:
        raise UserError('Complete actual northern land mask required, never a clipped rectangle')
    return buffered_columns(columns, 5), {'path': NORTH_MASK, 'sha256': NORTH_MASK_SHA,
        'north_columns': len(columns), 'extra_whole_crown_skirt': 5,
        'south_anchor': doc['independent_south_anchor_xz'], 'queries': doc['queries'],
        'outside_or_absence_is_not_south_authority': True}


def entity_positions(snapshot):
    """Six exact overworld members; no players/owners/raw entity NBT exported."""
    prefix = snapshot.prefix.removesuffix('region/')+'entities/'
    names = [prefix+f'r.{rx}.{rz}.mca' for rx in (1, 2) for rz in (-3, -2, -1)]
    names = [name for name in names if name in snapshot.files]
    if sum(snapshot.files[name]['size'] for name in names) > 32*1024**2:
        raise UserError('Finite saved entity occupancy allocation exceeded')
    rows, sources = [], []
    for name in names:
        record = snapshot.files[name]
        if snapshot.archive.getinfo(name).file_size != record['size']:
            raise UserError('Saved entity ZIP/member length differs')
        raw = snapshot.archive.read(name)
        if hashlib.sha256(raw).hexdigest() != record['sha256']:
            raise UserError('Saved entity member hash differs')
        region=tuple(map(int,Path(name).name.split('.')[1:3]))
        for document in decode_entity_chunks(raw,region):
            for root in document.get('Entities', []):
                for entity in entity_rows(root):
                    position = entity.get('Pos')
                    if not isinstance(position, list) or len(position) != 3 or any(type(v) not in (int, float) or not math.isfinite(v) for v in position):
                        raise UserError('Unknown saved entity position prevents an empty-plot screen')
                    rows.append((entity.get('id'), tuple(position)))
                    if len(rows) > 10000:
                        raise UserError('Finite entity position census exceeded')
        sources.append({'file': Path(name).name, 'bytes': len(raw), 'sha256': record['sha256']})
    return rows, sources


def near_entities(write, entities):
    # Conservative position screen, explicitly not a replacement for the live
    # native getEntities(writeBounds.inflate(1)) actual AABB admission.
    return [(kind, p) for kind, p in entities if all(write[i]-4 <= p[i] <= write[i+3]+5 for i in range(3))]


def overlap(a, b):
    return all(a[i] <= b[i+3] and b[i] <= a[i+3] for i in range(3))


def saved_plot(terrain, q, root, protected, entities):
    write, known = envelopes(root, q['relative_write_bounds'])
    protect_envelope(write, protected)
    column = terrain.column(root[0], root[2])
    if column.get('kind') != 'dry' or column.get('surface_y') != root[1]-1:
        raise UserError('Native root must use literal current ground plus one')
    if near_entities(write, entities):
        raise UserError('Saved resident/passenger/object position near plot; preserve it and choose another location')
    field = field_box(terrain, known)
    if pilot.base(field[tuple(root)]) not in AIR | pilot.NATIVE_SOFT or pilot.base(field[root[0], root[1]-1, root[2]]) not in pilot.ROOT_SOIL:
        raise UserError('Actual native root ground/replaceable cover required')
    retained_read_trees = 0
    for p, value in field.items():
        key = pilot.base(value)
        inside = all(write[i] <= p[i] <= write[i+3] for i in range(3))
        if not inside:
            retained_read_trees += int(is_tree(key))
            continue
        if p in terrain.entities or is_tree(key):
            raise UserError('Retain existing tree/BE in native WRITE envelope')
        if key in ('minecraft:water', 'minecraft:lava', 'minecraft:dirt_path') or 'waterlogged=true' in value:
            raise UserError('Retain water, wet roots and actual walking paths')
        if p[1] >= root[1] and key not in AIR | pilot.NATIVE_SOFT and not (p[1] <= root[1]+2 and key in GROUND):
            raise UserError('Retain actual crop, cliff obstruction or furnishing in native WRITE envelope')
    return field, write, known, retained_read_trees


def prepare(home, output, mode='followons', limit=12, checkpoint_id=None, checkpoint_sha256=None):
    home, output = Path(home).resolve(), Path(output).resolve()
    if output.exists() or not output.is_relative_to(home/'staging') or mode not in ('followons', 'copse', 'resume46') or not 1 <= limit <= 12:
        raise UserError('New owned finite native copse source required')
    if mode == 'resume46' and (checkpoint_id is None or checkpoint_sha256 is None):
        raise UserError('Remaining-six resume requires an explicit new verified recovery checkpoint')
    reserve = guard(1024**2, MAX_OUTPUT)
    budgets = [reader_budget()]
    current = read_json(home/'dashboard/settlement/backup-receipt.json')
    checkpoint_id = checkpoint_id or CHECKPOINT
    checkpoint_sha256 = checkpoint_sha256 or CHECKPOINT_SHA
    if current.get('verified') is not True or current.get('id') != checkpoint_id or current.get('sha256') != checkpoint_sha256:
        raise UserError('Explicit exact current post-native-tree checkpoint required')
    registry = read_json(home/'dashboard/settlement/registry.json')
    qvalues = pilot.qualifications(home) | all_qualifications(home)
    protected, custody, bank = pilot.protected_columns(home, registry)
    extra, proof = exclusions([(name, home/path, sha) for name, path, sha in NORTH], registry)
    protected.update(extra)
    custody += proof
    north, partition = north_partition(home, registry)
    protected.update(north)
    custody.append({'name': 'ALL exact northern connected land including unbuilt infill plus5m', 'sha256': NORTH_MASK_SHA})
    checkpoint = {'id': checkpoint_id, 'sha256': checkpoint_sha256, 'verified': True}
    terrain = ExtentTerrain(home, checkpoint, registry)
    docs, plots, refusals = {}, [], []
    started = time.monotonic()
    try:
        entities, entity_sources = entity_positions(terrain.snapshot)
        if mode == 'resume46':
            candidates = list(RESUME46_PLOTS)
        elif mode == 'followons':
            candidates = list(FOLLOWONS)
        else:
            candidates = []
            offsets = ((0, 0), (2, 1), (-1, 2), (1, -2), (-2, -1))
            bank_nodes = set(map(tuple, bank['bank_nodes_xz']))
            nodes = [row for row in bank['saved_samples'] if (row['x'], row['z']) in bank_nodes
                     and row['kind'] == 'dry']
            # Four interleaved broad contour bands; no straight row of stamps.
            nodes.sort(key=lambda r: ((r['x']//32*13+r['z']//32*7) % 29, r['z']//64, r['x']))
            for index, row in enumerate(nodes):
                ox, oz = offsets[index % len(offsets)]
                x, z = row['x']+ox, row['z']+oz
                col = terrain.column(x, z)
                if col.get('kind') != 'dry':
                    continue
                steps = max(abs(ox), abs(oz), 1)
                if any(terrain.column(row['x']+round(ox*n/steps), row['z']+round(oz*n/steps)).get('kind') != 'dry'
                       for n in range(steps+1)):
                    continue
                species = ('minecraft:birch_sapling', 'minecraft:birch_sapling', 'regions_unexplored:silver_birch_sapling',
                           'minecraft:birch_sapling', 'regions_unexplored:pine_sapling', 'regions_unexplored:larch_sapling')[index % 6]
                candidates.append(('copse-'+str(index+1), species, (x, col['surface_y']+1, z)))
                if len(candidates) >= 240:
                    break
        for ident, species, root in candidates:
            if len(plots) >= (3 if mode == 'followons' else limit):
                break
            if time.monotonic()-started > MAX_SECONDS:
                raise UserError('Finite native copse field producer expired; no generation/retry fallback')
            q = qvalues[species]
            write, known = envelopes(root, q['relative_write_bounds'])
            # READ fields may overlap. The new WRITE must not alter another
            # member's saved before field, in either sequential order.
            if any(overlap(write, p['known_bounds']) or overlap(known, p['write_bounds']) for p in plots):
                continue
            try:
                field, write, known, read_trees = saved_plot(terrain, q, root, protected, entities)
            except UserError as error:
                refusals.append({'id': ident, 'species': species, 'root': list(root), 'reason': str(error)})
                continue
            budgets.append(reader_budget())
            plan = {'format': 'awft-native-tree-plan:1', 'seed': registry['seed'], 'world_path': registry['world_path'],
                    'saplings': [species], 'root': list(root), 'write_bounds': write, 'known_bounds': known}
            docs[ident+'/tree-plan.json'] = encoded(plan)
            docs[ident+'/before-VERIFY-ONLY.json'] = encoded(settlement_plan(registry, checkpoint, field,
                'VERIFY ONLY exact native copse whole-field '+ident))
            docs[ident+'/qualification.json'] = encoded(q)
            plots.append({'id': ident, 'species': species, 'root': list(root), 'write_bounds': write, 'known_bounds': known,
                          'known_cells': len(field), 'read_only_retained_tree_cells': read_trees,
                          'native_live_aabb_clear': False, 'saved_position_screen_clear': True,
                          'potential_native_bee_slots': 3 if q['native_bee_nest_possible'] else 0,
                          'tree_plan_sha256': hashlib.sha256(docs[ident+'/tree-plan.json']).hexdigest()})
        sources = terrain.snapshot.sources.copy()
    finally:
        terrain.close()
    if not plots:
        raise UserError('No actual empty bounded native copse source plot; preserve all refusals')
    docs['protection.json'] = encoded({'format': 'awft-native-tree-protection:1', 'seed': registry['seed'],
        'world_path': registry['world_path'], 'minimum_buffer_blocks': 5, 'includes_latest_plaza_routes_and_walks': True,
        'columns': [list(p) for p in sorted(protected)], 'custody': custody})
    pins = pilot.runtime_pins(home)
    manifest = {'format': 'awft-native-copse-source:1', 'created': utcnow(), 'source_sha256': digest(Path(__file__)),
        'checkpoint_id': checkpoint_id, 'checkpoint_sha256': checkpoint_sha256, 'mode': mode, 'plots': plots,
        'runtime': pins, 'north_partition': partition, 'north_partition_verified': True,
        'resume46_historical_remaining_roots_only': mode == 'resume46',
        'resume46_excludes_prior_success_failed_restored_lost_and_changed_plots': mode == 'resume46',
        'whole_bank_south_source_sha256': pilot.checked(home/pilot.BANK/'manifest.json', pilot.BANK_MANIFEST_SHA, 1024**2)['proposal_sha256'],
        'entity_sources': entity_sources, 'saved_entities_screened': len(entities),
        'position_screen_is_not_actual_native_AABB_admission': True, 'native_guard_unchanged': True,
        'full_all_reachable_normal_rare_root_and_read_envelopes': True, 'read_context_trees_preserved_not_cleared': True,
        'potential_native_bee_slots': sum(p['potential_native_bee_slots'] for p in plots), 'refusals': refusals,
        'native_actions': 0, 'world_writes': 0, 'generation_requests_created': False, 'reserve_guard': reserve,
        'reader_budgets': budgets, 'source_regions': sources,
        'files': {name: {'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()} for name, raw in docs.items()}}
    docs['manifest.json'] = encoded(manifest)
    if sum(map(len, docs.values())) > MAX_OUTPUT:
        raise UserError('Finite native copse source output exceeded')
    output.mkdir(parents=True, exist_ok=False)
    for name, raw in docs.items():
        path = output/name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
    return {'directory': str(output), 'manifest_sha256': hashlib.sha256(docs['manifest.json']).hexdigest(),
            'plots': [{'id': p['id'], 'species': p['species'], 'root': p['root']} for p in plots], 'native_actions': 0}


def bind_requests(home, source_manifest, source_sha256, output, reviews):
    """Prepare only explicitly approved bare plots; never install or execute."""
    home, source_manifest, output = Path(home).resolve(), Path(source_manifest).resolve(), Path(output).resolve()
    if output.exists() or not output.is_relative_to(home/'staging') or not source_manifest.is_relative_to(home/'staging'):
        raise UserError('New owned request folder and exact source receipt required')
    reserve = guard(1024**2, 2*1024**2)
    source = pilot.checked(source_manifest, source_sha256, 1024**2)
    current = read_json(home/'dashboard/settlement/backup-receipt.json')
    if (source.get('format') != 'awft-native-copse-source:1' or source.get('world_writes') != 0
            or source.get('north_partition_verified') is not True or source.get('north_partition', {}).get('sha256') != NORTH_MASK_SHA
            or current.get('verified') is not True or current.get('id') != source['checkpoint_id']
            or current.get('sha256') != source['checkpoint_sha256']):
        raise UserError('Fresh exact copse source and stopped checkpoint required')
    north_partition(home, read_json(home/'dashboard/settlement/registry.json'))
    pins = pilot.runtime_pins(home)
    if pins['classes'] != source['runtime']['classes'] or pins['pack_sha256'] != source['runtime']['pack_sha256']:
        raise UserError('Actual compiled native guards/pack changed')
    plots = {p['id']: p for p in source['plots']}
    if not reviews or not set(reviews) <= plots.keys():
        raise UserError('Explicit nonempty subset of reviewed source plots required')
    docs, requests = {}, []
    for ident, ready_path in reviews.items():
        plot = plots[ident]
        ready_ref = pilot.owned_ref(home, ready_path)
        if not 0 < ready_ref['bytes'] <= 128*1024:
            raise UserError('Bounded exact plot readiness required')
        ready = read_json(Path(ready_path))
        if (ready.get('approval_scope') != 'one-exact-saved-tree-plot'
                or ready.get('checkpoint_sha256') != source['checkpoint_sha256']
                or ready.get('tree_plan_sha256') != plot['tree_plan_sha256']
                or any(ready.get(k) is not True for k in ('construction_complete', 'functional_commissioning_complete', 'visual_corrections_reviewed'))):
            raise UserError('Truthful bare-plot readiness required; no whole-world completion fallback')
        refs = {}
        for role, name in (('plan', ident+'/tree-plan.json'), ('before', ident+'/before-VERIFY-ONLY.json'),
                           ('qualification', ident+'/qualification.json'), ('protection', 'protection.json')):
            member = source['files'][name]
            path = source_manifest.parent/name
            if path.stat().st_size != member['bytes']:
                raise UserError('Copse proof member size differs')
            pilot.checked(path, member['sha256'], MAX_OUTPUT)
            refs[role] = pilot.owned_ref(home, path)
        request = {'format': 'awft-native-trees:1', 'allowed_operation': 'grow',
            **{k: pins[k] for k in ('candidate_version', 'bridge_version', 'pack_sha256')},
            **{k: value for k, value in pins['classes'].items() if k.startswith('native_')},
            'checkpoint_sha256': source['checkpoint_sha256'],
            'current_backup': pilot.owned_ref(home, home/'dashboard/settlement/backup-receipt.json'),
            **refs, 'construction_ready': ready_ref}
        raw = encoded(request)
        sha = hashlib.sha256(raw).hexdigest()
        bundle = 'trees-'+sha[:16]
        docs[bundle+'/request.json'] = raw
        requests.append({'id': ident, 'bundle': bundle, 'sha256': sha})
    receipt = {'format': 'awft-native-copse-binding:1', 'source_manifest_sha256': source_sha256,
        'source_sha256': digest(Path(__file__)), 'checkpoint_sha256': source['checkpoint_sha256'],
        'requests': requests, 'approval_created': False, 'installed': False, 'native_actions': 0, 'reserve_guard': reserve}
    docs['binding-receipt.json'] = encoded(receipt)
    if sum(map(len, docs.values())) > 2*1024**2:
        raise UserError('Finite copse request output exceeded')
    output.mkdir(parents=True, exist_ok=False)
    for name, raw in docs.items():
        path = output/name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
    return {'directory': str(output), 'binding_sha256': hashlib.sha256(docs['binding-receipt.json']).hexdigest(),
            'requests': requests, 'native_actions': 0}
